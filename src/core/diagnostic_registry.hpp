consteval std::uint64_t structural_diagnostic_token_hash(const std::string_view token) {
  std::uint64_t hash = 14695981039346656037ULL;
  for (const char character : token) {
    hash ^= static_cast<unsigned char>(character);
    hash *= 1099511628211ULL;
  }
  return hash;
}

consteval bool structural_diagnostic_registry_is_unique() {
  std::array<std::uint32_t, kStructuralDiagnosticRegistry.size()> ids{};
  std::array<std::uint64_t, kStructuralDiagnosticRegistry.size()> token_hashes{};
  for (std::size_t index = 0; index < kStructuralDiagnosticRegistry.size(); ++index) {
    ids[index] = static_cast<std::uint32_t>(kStructuralDiagnosticRegistry[index].id);
    token_hashes[index] =
        structural_diagnostic_token_hash(kStructuralDiagnosticRegistry[index].token);
  }
  std::ranges::sort(ids);
  std::ranges::sort(token_hashes);
  for (std::size_t index = 1; index < kStructuralDiagnosticRegistry.size(); ++index) {
    if (ids[index - 1U] == ids[index] || token_hashes[index - 1U] == token_hashes[index]) {
      return false;
    }
  }
  return true;
}

static_assert(structural_diagnostic_registry_is_unique(),
              "structural diagnostic ids and tokens must be globally unique");

[[nodiscard]] constexpr DiagnosticId diagnostic_id(std::string_view token) noexcept {
  for (const auto& descriptor : kStructuralDiagnosticRegistry) {
    if (descriptor.token == token) {
      return DiagnosticId{static_cast<std::uint32_t>(descriptor.id)};
    }
  }
  return {};
}

[[nodiscard]] constexpr const StructuralDiagnosticDescriptor* find_structural_diagnostic(
    StructuralDiagnosticId id) {
  for (const auto& descriptor : kStructuralDiagnosticRegistry) {
    if (descriptor.id == id) {
      return &descriptor;
    }
  }
  return nullptr;
}

[[nodiscard]] constexpr bool requires_field(const StructuralDiagnosticDescriptor& descriptor,
                                            DiagnosticPayloadField field) noexcept {
  const DiagnosticFieldMask field_mask = diagnostic_field_mask(field);
  return (descriptor.required_fields.low & field_mask.low) != 0U ||
         (descriptor.required_fields.high & field_mask.high) != 0U;
}

