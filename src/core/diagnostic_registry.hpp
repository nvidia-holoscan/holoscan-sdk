struct DiagnosticFieldMask {
  std::uint64_t low{};
  std::uint64_t high{};

  friend constexpr bool operator==(const DiagnosticFieldMask&,
                                   const DiagnosticFieldMask&) = default;
};

[[nodiscard]] constexpr DiagnosticFieldMask operator|(DiagnosticFieldMask left,
                                                      DiagnosticFieldMask right) noexcept {
  return DiagnosticFieldMask{left.low | right.low, left.high | right.high};
}

[[nodiscard]] constexpr DiagnosticFieldMask diagnostic_field_mask(
    DiagnosticPayloadField field) noexcept {
  const auto index = static_cast<std::uint8_t>(field);
  if (index < 64U) {
    return DiagnosticFieldMask{std::uint64_t{1} << index, 0U};
  }
  return DiagnosticFieldMask{0U, std::uint64_t{1} << (index - 64U)};
}

