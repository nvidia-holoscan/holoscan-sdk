# The native extension is intentionally flat. This private storage name avoids colliding with the
# distinct public ``holoscan.tensor.TensorLoan`` while the facade exposes the canonical name.
_NATIVE_ALIASES = {("holoscan.channel", "TensorLoan"): "_ChannelTensorLoan"}

# Reusable Graph proxies intentionally add names from the process-local registry at runtime. The
# fixed public vocabulary remains represented in PUBLIC_API.
DYNAMIC_PUBLIC_MODULES = frozenset({"holoscan.graphs"})


def public_api_names(module_name: str) -> list[str]:
    """Return the fixed public names declared for one Python module."""

    return list(PUBLIC_API[module_name])


def export_public_names(module_name: str, namespace: MutableMapping[str, Any]) -> list[str]:
    """Populate a public facade from the native extension and return its export list."""

    names = public_api_names(module_name)
    namespace.update(
        {name: getattr(_core, _NATIVE_ALIASES.get((module_name, name), name)) for name in names}
    )
    return names


__all__ = ["DYNAMIC_PUBLIC_MODULES", "PUBLIC_API"]
