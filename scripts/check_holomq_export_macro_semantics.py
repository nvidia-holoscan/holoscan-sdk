import argparse
import json
import re
import sys
from pathlib import Path

PUBLIC_HEADER_ROOT = Path("include/holomq")
EXPORT_MACRO = "HOLOMQ_EXPORT"
HEADER_SUFFIXES = {".h", ".hh", ".hpp", ".hxx"}
DECLARATION_RE = re.compile(
    r"^\s*(?!#)(?!using\b)(?!typedef\b)(?!return\b)"
    r"(?!inline\b)(?!constexpr\b)(?!static\b)(?!friend\b)"
    r"(?:[A-Za-z_][A-Za-z0-9_:<>~,\s*&]+)\s+"
    r"[A-Za-z_~][A-Za-z0-9_:~]*\s*\([^;{}]*\)\s*(?:const\s*)?(?:noexcept\s*)?;"
)


def load_compile_commands(path: Path) -> list[dict[str, object]]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise RuntimeError(f"cannot read compile commands: {path}: {error}") from error
    except json.JSONDecodeError as error:
        raise RuntimeError(f"invalid JSON compile commands: {path}: {error}") from error

    if not isinstance(data, list):
        raise RuntimeError(f"compile commands must be a JSON list: {path}")
    return data


def public_headers(root: Path) -> list[Path]:
    header_root = root / PUBLIC_HEADER_ROOT
    if not header_root.exists():
        return []
    return [
        path
        for path in header_root.rglob("*")
        if path.suffix in HEADER_SUFFIXES and "detail" not in path.parts
    ]


def check_header(path: Path) -> list[str]:
    errors: list[str] = []
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        stripped = line.strip()
        if not stripped or EXPORT_MACRO in stripped:
            continue
        if DECLARATION_RE.match(line):
            errors.append(
                f"{path}:{line_number}: exported function declaration lacks {EXPORT_MACRO}"
            )
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Run HoloMQ public-header export macro semantic checks. "
            "Only include/holomq headers are inspected."
        )
    )
    parser.add_argument("--root", default=".", help="HoloMQ module root to scan.")
    parser.add_argument(
        "--compile-commands",
        help="Optional path to compile_commands.json generated by CMake.",
    )
    args = parser.parse_args()

    if args.compile_commands:
        compile_commands = Path(args.compile_commands)
        try:
            load_compile_commands(compile_commands)
        except RuntimeError as error:
            print(f"ERROR: {error}")
            return 1

    root = Path(args.root)
    errors: list[str] = []
    for path in public_headers(root):
        errors.extend(check_header(path))

    if errors:
        print("HoloMQ export macro semantic policy failed:")
        for error in errors:
            print(f"  {error}")
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
